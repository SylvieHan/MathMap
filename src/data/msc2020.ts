export function searchMsc(query: string): MscEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return MSC2020.filter((e) => !e.parent).slice(0, 20);
  return MSC2020.filter(
    (e) =>
      e.code.toLowerCase().includes(q) ||
      e.label.toLowerCase().includes(q),
  ).slice(0, 30);
}

export function getMscLabel(code: string): string {
  const entry = MSC2020.find((e) => e.code === code);
  return entry ? `${code} — ${entry.label}` : code;
}

export function getTopLevelCode(code: string): string {
  const digits = code.replace(/\D/g, '');
  return digits.slice(0, 2).padStart(2, '0');
}
